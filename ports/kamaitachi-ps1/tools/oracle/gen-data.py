#!/usr/bin/env python3
"""Usage: python3 tools/oracle/gen-data.py <SLPS_017.94> > sound/lib/data.js
Writes the libsnd/libspu initialised data (default registers, tick set-up, pitch table and the RAM below it,
SPU pointers and alignment, reverb work areas and presets) as JS, so sound/lib runs
without the EXE. Only these library tables are taken; no game data."""
import struct, sys

TABLES = [
    # libetc/libapi data below the pitch table: the pitch lookup reads it for notes under
    # the table (see sound/lib/platform.js). Hardware register pointers and a build stamp.
    (0x80078540, 0xec, "libetc/libapi data read by the pitch lookup for notes under its table"),
    (0x8007862c, 0x30, "voice and common register defaults (0x80055e38)"),
    # 0x80078660-0x8007869f: tick mode, interrupt flags, tick callback, I_STAT and root
    # counter pointers and counter mode bits. The pitch lookup (0x8005bf88/0x8005c05c)
    # also reads these words as table entries for notes below the table.
    (0x80078660, 0x40, "tick set-up and root counter bits"),
    (0x800786a0, 0x180, "pitch table: 12 semitones x 16 fine steps (0x8005bf88)"),
    (0x80078cb0, 0x50, "SPU/DMA register pointers, address shift and alignment, transfer state, init block"),
    (0x80078d20, 0x2f8, "reverb work-area starts and 68-byte register presets per mode"),
]
exe = open(sys.argv[1], "rb").read()
base = struct.unpack_from("<I", exe, 0x18)[0]
print("// Generated by tools/oracle/gen-data.py: the sound libraries' initialised data, which the")
print("// original reads from its data section. [address, words] pairs, little-endian words.")
print("export const INIT_DATA = [")
for addr, size, what in TABLES:
    words = struct.unpack_from("<%dI" % (size // 4), exe, addr - base + 0x800)
    print("  // %s" % what)
    print("  [0x%08x, [" % addr)
    for i in range(0, len(words), 8):
        print("    " + ", ".join("0x%x" % w for w in words[i:i + 8]) + ",")
    print("  ]],")
print("];")
